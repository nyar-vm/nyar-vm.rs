//! Product-side install layout adapter: PM `vendors/` → Node `node_modules/`.
//!
//! PM keeps packages under `vendors/{registry}/{name}@{version}`. Noodle
//! materializes a resolve tree for classic Node — without teaching the PM
//! about npm/pnpm layouts, and **without** shelling to the pnpm CLI.
//!
//! - **npm / yarn / bun compat:** flat `node_modules/{name}` (Option B).
//! - **pnpm compat:** A-lite pnpm-like tree — `node_modules/.pnpm/{id}/node_modules/{name}`
//!   virtual store + top-level symlinks. 自研 adapter ≠ pnpm CLI.

use std::{
    collections::BTreeSet,
    fs, io,
    path::{Path, PathBuf},
};

#[cfg(unix)]
use std::path::Component;

use miette::{IntoDiagnostic, Result, WrapErr, miette};
use nyar_package_manager::LockFile;

use crate::{layout::project_layout, project::PmCompat};

/// Foreign lockfiles noodle never reads for install or compat selection.
pub const FOREIGN_LOCKFILES: &[&str] = &["package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock", "bun.lockb"];

/// Virtual-store directory name under `node_modules` (pnpm-like; noodle-owned).
pub const PNPM_STORE_DIR: &str = ".pnpm";

/// Result of materializing `node_modules` from the noodle lockfile.
#[derive(Debug, Clone, Default)]
pub struct MaterializeReport {
    /// Packages linked or copied into `node_modules`.
    pub linked: usize,
    /// How many entries used copy because symlink/junction failed.
    pub copied: usize,
    /// Package names that were linked.
    pub names: Vec<String>,
    /// Layout style that was written.
    pub layout: LayoutKind,
}

/// On-disk `node_modules` shape chosen from [`PmCompat`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum LayoutKind {
    /// Flat top-level links (npm-style).
    #[default]
    Flat,
    /// `.pnpm` virtual store + top-level links (pnpm-like A-lite).
    PnpmLike,
}

impl LayoutKind {
    /// Pick layout from product compat (not from lockfile sniffing).
    pub fn from_compat(compat: PmCompat) -> Self {
        match compat {
            PmCompat::Pnpm => Self::PnpmLike,
            PmCompat::Npm | PmCompat::Yarn | PmCompat::Bun => Self::Flat,
        }
    }

    /// Short label for logs.
    pub fn label(self) -> &'static str {
        match self {
            Self::Flat => "flat",
            Self::PnpmLike => "pnpm-like",
        }
    }
}

/// Print a one-line note when classic npm/pnpm/yarn lockfiles are present.
///
/// Policy: ignore them. Compat comes from `package.json` (`noodle.compat` /
/// `packageManager`); the source of truth for installs is `noodle-lock.von`.
pub fn note_foreign_lockfiles(root: &Path) {
    let present: Vec<&str> = FOREIGN_LOCKFILES.iter().copied().filter(|name| root.join(name).is_file()).collect();
    if present.is_empty() {
        return;
    }
    eprintln!("note: ignoring {}; noodle uses noodle-lock.von (compat from package.json params, not lockfile sniffing)", present.join(", "));
}

/// Rebuild `node_modules/` from `noodle-lock.von` + `vendors/` using flat layout.
pub fn materialize_node_modules(root: &Path) -> Result<MaterializeReport> {
    materialize_node_modules_for(root, LayoutKind::Flat)
}

/// Rebuild `node_modules/` for the given product layout kind.
pub fn materialize_node_modules_for(root: &Path, layout: LayoutKind) -> Result<MaterializeReport> {
    match layout {
        LayoutKind::Flat => materialize_flat(root),
        LayoutKind::PnpmLike => materialize_pnpm_like(root),
    }
}

/// Rebuild using [`PmCompat`] (pnpm → pnpm-like; otherwise flat).
pub fn materialize_for_compat(root: &Path, compat: PmCompat) -> Result<MaterializeReport> {
    materialize_node_modules_for(root, LayoutKind::from_compat(compat))
}

fn materialize_flat(root: &Path) -> Result<MaterializeReport> {
    let lock = LockFile::load(root, project_layout()).into_diagnostic().wrap_err("读取 noodle-lock.von 失败")?;
    let nm = root.join("node_modules");
    // Drop leftover pnpm-like store when switching compat → flat.
    remove_path_if_exists(&nm.join(PNPM_STORE_DIR))?;
    fs::create_dir_all(&nm).into_diagnostic()?;

    let mut wanted: BTreeSet<PathBuf> = BTreeSet::new();
    let mut report = MaterializeReport { layout: LayoutKind::Flat, ..Default::default() };

    for entry in lock.packages.values() {
        let vendor = vendor_path(root, entry);
        ensure_vendor(&vendor, entry)?;
        let link = node_modules_package_path(&nm, &entry.name);
        if let Some(parent) = link.parent() {
            fs::create_dir_all(parent).into_diagnostic()?;
        }
        let used_copy = link_or_copy(&vendor, &link)?;
        if used_copy {
            report.copied += 1;
        }
        report.linked += 1;
        report.names.push(entry.name.clone());
        mark_wanted_package(&mut wanted, &nm, &link);
    }

    prune_stale_node_modules(&nm, &wanted, false)?;
    report.names.sort();
    Ok(report)
}

/// A-lite pnpm-like layout (自研; not the pnpm CLI).
///
/// ```text
/// node_modules/
///   .pnpm/
///     left-pad@1.3.0/node_modules/left-pad     → vendors/…
///     @scope+pkg@2.0.0/node_modules/@scope/pkg → vendors/…
///   left-pad → .pnpm/left-pad@1.3.0/node_modules/left-pad
///   @scope/pkg → .pnpm/@scope+pkg@2.0.0/node_modules/@scope/pkg
/// ```
fn materialize_pnpm_like(root: &Path) -> Result<MaterializeReport> {
    let lock = LockFile::load(root, project_layout()).into_diagnostic().wrap_err("读取 noodle-lock.von 失败")?;
    let nm = root.join("node_modules");
    let store = nm.join(PNPM_STORE_DIR);
    fs::create_dir_all(&store).into_diagnostic()?;

    let mut wanted: BTreeSet<PathBuf> = BTreeSet::new();
    let mut wanted_store: BTreeSet<PathBuf> = BTreeSet::new();
    let mut report = MaterializeReport { layout: LayoutKind::PnpmLike, ..Default::default() };

    for entry in lock.packages.values() {
        let vendor = vendor_path(root, entry);
        ensure_vendor(&vendor, entry)?;

        let store_id = pnpm_store_id(&entry.name, &entry.version);
        let store_pkg = store.join(&store_id).join("node_modules").join(&entry.name);
        if let Some(parent) = store_pkg.parent() {
            fs::create_dir_all(parent).into_diagnostic()?;
        }
        let used_copy = link_or_copy(&vendor, &store_pkg)?;
        if used_copy {
            report.copied += 1;
        }

        let top = node_modules_package_path(&nm, &entry.name);
        if let Some(parent) = top.parent() {
            fs::create_dir_all(parent).into_diagnostic()?;
        }
        // Prefer linking top-level → store entry (pnpm shape). Fall back to vendor.
        let used_copy_top = link_or_copy(&store_pkg, &top).or_else(|_| link_or_copy(&vendor, &top))?;
        if used_copy_top {
            report.copied += 1;
        }

        report.linked += 1;
        report.names.push(entry.name.clone());
        mark_wanted_package(&mut wanted, &nm, &top);
        wanted_store.insert(store.join(&store_id));
        // Keep intermediate dirs under the store entry.
        wanted_store.insert(store.join(&store_id).join("node_modules"));
        if let Some(parent) = store_pkg.parent() {
            if parent != store.join(&store_id).join("node_modules") {
                wanted_store.insert(parent.to_path_buf());
            }
        }
        wanted_store.insert(store_pkg);
    }

    prune_stale_node_modules(&nm, &wanted, true)?;
    prune_pnpm_store(&store, &wanted_store)?;
    report.names.sort();
    Ok(report)
}

fn ensure_vendor(vendor: &Path, entry: &nyar_package_manager::LockEntry) -> Result<()> {
    if vendor.is_dir() {
        return Ok(());
    }
    Err(miette!("缺少 vendors 包目录 {}（{}@{}）；请重新 noodle install", vendor.display(), entry.name, entry.version))
}

fn mark_wanted_package(wanted: &mut BTreeSet<PathBuf>, nm: &Path, link: &Path) {
    if let Some(parent) = link.parent() {
        if parent != nm {
            wanted.insert(parent.to_path_buf());
        }
    }
    wanted.insert(link.to_path_buf());
}

/// pnpm-style store folder id: `name@version` or `@scope+name@version`.
pub fn pnpm_store_id(name: &str, version: &str) -> String {
    let folder_name = name.replace('/', "+");
    format!("{folder_name}@{version}")
}

/// Remove `node_modules/{name}` for a single package.
pub fn unlink_node_modules_package(root: &Path, package_name: &str) -> Result<()> {
    let link = node_modules_package_path(&root.join("node_modules"), package_name);
    remove_path_if_exists(&link)?;
    if let Some(parent) = link.parent() {
        if parent.file_name().and_then(|s| s.to_str()).is_some_and(|s| s.starts_with('@')) {
            let _ = fs::remove_dir(parent);
        }
    }
    Ok(())
}

fn vendor_path(root: &Path, entry: &nyar_package_manager::LockEntry) -> PathBuf {
    let vendors = root.join("vendors");
    if entry.is_workspace || entry.registry == "workspace" {
        return vendors.join(&entry.name);
    }
    if !entry.install_path.is_empty() {
        return vendors.join(&entry.install_path);
    }
    if !entry.registry.is_empty() {
        return vendors.join(format!("{}/{}@{}", entry.registry, entry.name, entry.version));
    }
    vendors.join(&entry.name)
}

fn node_modules_package_path(node_modules: &Path, name: &str) -> PathBuf {
    node_modules.join(name)
}

/// Returns `true` when the destination was populated via copy (not link).
fn link_or_copy(target: &Path, link: &Path) -> Result<bool> {
    remove_path_if_exists(link)?;
    if let Some(parent) = link.parent() {
        fs::create_dir_all(parent).into_diagnostic()?;
    }

    let target_abs = fs::canonicalize(target).into_diagnostic().wrap_err_with(|| format!("规范化 {}", target.display()))?;

    #[cfg(unix)]
    {
        let parent = link.parent().unwrap_or_else(|| Path::new("."));
        let rel = path_relative_from(parent, &target_abs);
        if std::os::unix::fs::symlink(&rel, link).is_ok() {
            return Ok(false);
        }
        if std::os::unix::fs::symlink(&target_abs, link).is_ok() {
            return Ok(false);
        }
    }

    #[cfg(windows)]
    {
        if std::os::windows::fs::symlink_dir(&target_abs, link).is_ok() {
            return Ok(false);
        }
    }

    copy_dir_recursive(&target_abs, link)
        .into_diagnostic()
        .wrap_err_with(|| format!("无法链接或复制 {} → {}", target_abs.display(), link.display()))?;
    Ok(true)
}

fn prune_stale_node_modules(node_modules: &Path, wanted: &BTreeSet<PathBuf>, keep_dot_pnpm: bool) -> Result<()> {
    if !node_modules.is_dir() {
        return Ok(());
    }
    prune_dir(node_modules, wanted, keep_dot_pnpm)
}

fn prune_dir(dir: &Path, wanted: &BTreeSet<PathBuf>, keep_dot_pnpm: bool) -> Result<()> {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return Ok(()),
    };
    for entry in entries {
        let entry = entry.into_diagnostic()?;
        let path = entry.path();
        let name = entry.file_name();
        let name_str = name.to_string_lossy();
        if name_str == PNPM_STORE_DIR {
            if keep_dot_pnpm {
                continue;
            }
            remove_path_if_exists(&path)?;
            continue;
        }
        if name_str.starts_with('.') {
            continue;
        }
        if name_str.starts_with('@') && path.is_dir() && !path.is_symlink() {
            prune_dir(&path, wanted, keep_dot_pnpm)?;
            if fs::read_dir(&path).map(|mut i| i.next().is_none()).unwrap_or(false) {
                let _ = fs::remove_dir(&path);
            }
            continue;
        }
        if !wanted.contains(&path) {
            remove_path_if_exists(&path)?;
        }
    }
    Ok(())
}

fn prune_pnpm_store(store: &Path, wanted: &BTreeSet<PathBuf>) -> Result<()> {
    if !store.is_dir() {
        return Ok(());
    }
    let entries = match fs::read_dir(store) {
        Ok(e) => e,
        Err(_) => return Ok(()),
    };
    for entry in entries {
        let entry = entry.into_diagnostic()?;
        let path = entry.path();
        if !wanted.contains(&path) {
            remove_path_if_exists(&path)?;
        }
    }
    Ok(())
}

fn remove_path_if_exists(path: &Path) -> Result<()> {
    if !path.exists() && !path.is_symlink() {
        return Ok(());
    }
    let meta = fs::symlink_metadata(path).into_diagnostic()?;
    if meta.file_type().is_dir() && !meta.file_type().is_symlink() {
        fs::remove_dir_all(path).into_diagnostic()?;
    }
    else {
        fs::remove_file(path).or_else(|_| fs::remove_dir_all(path)).into_diagnostic()?;
    }
    Ok(())
}

fn copy_dir_recursive(src: &Path, dst: &Path) -> io::Result<()> {
    fs::create_dir_all(dst)?;
    for entry in fs::read_dir(src)? {
        let entry = entry?;
        let ty = entry.file_type()?;
        let to = dst.join(entry.file_name());
        if ty.is_dir() {
            copy_dir_recursive(&entry.path(), &to)?;
        }
        else if ty.is_symlink() {
            continue;
        }
        else {
            fs::copy(entry.path(), to)?;
        }
    }
    Ok(())
}

#[cfg(unix)]
fn path_relative_from(from_dir: &Path, to: &Path) -> PathBuf {
    let from = fs::canonicalize(from_dir).unwrap_or_else(|_| from_dir.to_path_buf());
    let to = fs::canonicalize(to).unwrap_or_else(|_| to.to_path_buf());
    let from_comps: Vec<Component> = from.components().collect();
    let to_comps: Vec<Component> = to.components().collect();
    let mut i = 0;
    while i < from_comps.len() && i < to_comps.len() && from_comps[i] == to_comps[i] {
        i += 1;
    }
    let mut out = PathBuf::new();
    for _ in i..from_comps.len() {
        out.push("..");
    }
    for comp in &to_comps[i..] {
        out.push(comp.as_os_str());
    }
    if out.as_os_str().is_empty() { PathBuf::from(".") } else { out }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::{Mutex, OnceLock};

    use nyar_package_manager::{LockEntry, LockFile};
    use tempfile::TempDir;

    fn env_lock() -> &'static Mutex<()> {
        static LOCK: OnceLock<Mutex<()>> = OnceLock::new();
        LOCK.get_or_init(|| Mutex::new(()))
    }

    fn with_isolated_home<T>(f: impl FnOnce() -> T) -> T {
        let _guard = env_lock().lock().expect("env lock");
        let home = TempDir::new().expect("temp home");
        let prev = std::env::var_os("NOODLE_HOME");
        unsafe {
            std::env::set_var("NOODLE_HOME", home.path());
        }
        let result = f();
        unsafe {
            match prev {
                Some(v) => std::env::set_var("NOODLE_HOME", v),
                None => std::env::remove_var("NOODLE_HOME"),
            }
        }
        result
    }

    fn seed_vendor(root: &Path, registry: &str, name: &str, version: &str) -> PathBuf {
        let vendor = root.join("vendors").join(registry).join(format!("{name}@{version}"));
        fs::create_dir_all(&vendor).unwrap();
        fs::write(vendor.join("index.js"), "module.exports = 1;\n").unwrap();
        fs::write(vendor.join("package.json"), format!("{{\"name\":\"{name}\",\"version\":\"{version}\"}}\n")).unwrap();
        vendor
    }

    fn write_lock(root: &Path, entries: &[(&str, &str, &str)]) {
        let mut lock = LockFile::new(root, project_layout());
        for (registry, name, version) in entries {
            lock.packages.insert(
                LockFile::package_key(name, version),
                LockEntry {
                    name: (*name).into(),
                    version: (*version).into(),
                    registry: (*registry).into(),
                    install_path: format!("{registry}/{name}@{version}"),
                    ..LockEntry::default()
                },
            );
        }
        lock.save().unwrap();
    }

    #[test]
    fn materialize_links_flat_and_scoped_packages() {
        with_isolated_home(|| {
            let dir = TempDir::new().unwrap();
            let root = dir.path();
            seed_vendor(root, "npm", "left-pad", "1.3.0");
            seed_vendor(root, "npm", "@scope/pkg", "2.0.0");
            write_lock(root, &[("npm", "left-pad", "1.3.0"), ("npm", "@scope/pkg", "2.0.0")]);

            let report = materialize_node_modules(root).unwrap();
            assert_eq!(report.layout, LayoutKind::Flat);
            assert_eq!(report.linked, 2);
            assert!(root.join("node_modules").join("left-pad").join("index.js").is_file());
            assert!(root.join("node_modules").join("@scope").join("pkg").join("index.js").is_file());
            assert!(!root.join("node_modules").join(PNPM_STORE_DIR).exists());
        });
    }

    #[test]
    fn materialize_prunes_stale_entries() {
        with_isolated_home(|| {
            let dir = TempDir::new().unwrap();
            let root = dir.path();
            seed_vendor(root, "npm", "keep-me", "1.0.0");
            write_lock(root, &[("npm", "keep-me", "1.0.0")]);

            let stale = root.join("node_modules").join("stale-pkg");
            fs::create_dir_all(&stale).unwrap();
            fs::write(stale.join("x.js"), "1").unwrap();

            materialize_node_modules(root).unwrap();
            assert!(root.join("node_modules").join("keep-me").exists());
            assert!(!root.join("node_modules").join("stale-pkg").exists());
        });
    }

    #[test]
    fn pnpm_like_uses_virtual_store_and_top_links() {
        with_isolated_home(|| {
            let dir = TempDir::new().unwrap();
            let root = dir.path();
            seed_vendor(root, "npm", "left-pad", "1.3.0");
            seed_vendor(root, "npm", "@scope/pkg", "2.0.0");
            write_lock(root, &[("npm", "left-pad", "1.3.0"), ("npm", "@scope/pkg", "2.0.0")]);

            let report = materialize_for_compat(root, PmCompat::Pnpm).unwrap();
            assert_eq!(report.layout, LayoutKind::PnpmLike);
            assert_eq!(report.linked, 2);

            let store_left = root.join("node_modules").join(PNPM_STORE_DIR).join("left-pad@1.3.0").join("node_modules").join("left-pad");
            assert!(store_left.join("index.js").is_file());

            let store_scoped =
                root.join("node_modules").join(PNPM_STORE_DIR).join("@scope+pkg@2.0.0").join("node_modules").join("@scope").join("pkg");
            assert!(store_scoped.join("index.js").is_file());

            assert!(root.join("node_modules").join("left-pad").join("index.js").is_file());
            assert!(root.join("node_modules").join("@scope").join("pkg").join("index.js").is_file());
        });
    }

    #[test]
    fn pnpm_compat_from_package_manager_selects_layout() {
        assert_eq!(LayoutKind::from_compat(PmCompat::Pnpm), LayoutKind::PnpmLike);
        assert_eq!(LayoutKind::from_compat(PmCompat::Npm), LayoutKind::Flat);
    }

    #[test]
    fn pnpm_store_id_encodes_scope() {
        assert_eq!(pnpm_store_id("left-pad", "1.0.0"), "left-pad@1.0.0");
        assert_eq!(pnpm_store_id("@scope/pkg", "2.0.0"), "@scope+pkg@2.0.0");
    }

    #[test]
    fn foreign_lockfile_names_are_documented() {
        assert!(FOREIGN_LOCKFILES.contains(&"package-lock.json"));
        assert!(FOREIGN_LOCKFILES.contains(&"pnpm-lock.yaml"));
    }
}
